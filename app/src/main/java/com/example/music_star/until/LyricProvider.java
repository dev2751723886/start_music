    // 把纯歌词（每行一句）转成 LRC：自动均匀分配时间戳，每句 intervalSec 秒
    private static String toLrc(String plainText, int intervalSec) {
        String[] lines = plainText.split("\n");
        StringBuilder sb = new StringBuilder();
        int idx = 0;
        for (String raw : lines) {
            String line = raw.trim();
            if (line.isEmpty()) {
                continue;
            }
            int total = idx * intervalSec;
            sb.append("[").append(two(total / 60)).append(":")
              .append(two(total % 60)).append(".00]")
              .append(line).append("\n");
            idx++;
        }
        return sb.toString();
    }

    private static String two(int n) {
        return n < 10 ? "0" + n : String.valueOf(n);
    }

    public static String getLrc(String musicId) {
        return LRC.get(musicId);
    }
